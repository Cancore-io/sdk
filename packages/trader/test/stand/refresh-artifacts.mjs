/**
 * Refreshes `artifacts.json`: the build of the three contracts the anvil stand
 * of this repository's CI deploys (CancoreRouter, MockPermit2, TestToken), from
 * a checkout of the private evm-contracts at a reviewed commit (operator
 * decision Ыу-1, CAN-1846). CI never sees evm-contracts: it deploys these bytes.
 *
 *   (cd <evm-contracts> && git checkout <commit> && npm ci && npx hardhat compile)
 *   node packages/trader/test/stand/refresh-artifacts.mjs <evm-contracts>
 *
 * Refuses a dirty checkout, and a CancoreRouter whose creation code is not the
 * one evm-contracts pins in `abi/bytecode-hashes.json` at that commit.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { keccak256 } from 'ethers';

const root = process.argv[2];
if (!root) throw new Error('usage: refresh-artifacts.mjs <evm-contracts checkout>');

const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' }).trim();
if (git('status', '--porcelain', '--untracked-files=no')) throw new Error(`${root} has uncommitted changes: build from a commit`);
const commit = git('rev-parse', 'HEAD');

const artifact = (file) => JSON.parse(readFileSync(join(root, 'artifacts', file), 'utf8'));
const router = artifact('contracts/CancoreRouter.sol/CancoreRouter.json');
const permit2 = artifact('contracts/mocks/MockPermit2.sol/MockPermit2.json');
const token = artifact('contracts/test/TestToken.sol/TestToken.json');

// evm-contracts' own bytecode baseline (scripts/tools/check-bytecode-match.mjs): sha256 of the hex string.
const pinned = JSON.parse(readFileSync(join(root, 'abi/bytecode-hashes.json'), 'utf8')).CancoreRouter;
const sha256 = createHash('sha256').update(router.bytecode).digest('hex');
if (sha256 !== pinned?.bytecodeHash) throw new Error(`CancoreRouter build ${sha256} is not the pinned ${pinned?.bytecodeHash}: compile the commit as it is`);
if (Object.keys(permit2.immutableReferences ?? {}).length > 0) throw new Error('MockPermit2 has immutables: its runtime code cannot be placed with anvil_setCode');

const out = {
  $comment: 'Generated by refresh-artifacts.mjs from Cancore-io/evm-contracts; never edit by hand. Deployed on anvil by up.mjs.',
  source: { repository: 'Cancore-io/evm-contracts', commit },
  CancoreRouter: { abi: router.abi, bytecode: router.bytecode, bytecodeHash: keccak256(router.bytecode), sha256 },
  MockPermit2: { deployedBytecode: permit2.deployedBytecode, deployedBytecodeHash: keccak256(permit2.deployedBytecode) },
  TestToken: { abi: token.abi, bytecode: token.bytecode, bytecodeHash: keccak256(token.bytecode) },
};
const target = join(dirname(fileURLToPath(import.meta.url)), 'artifacts.json');
writeFileSync(target, `${JSON.stringify(out, null, 2)}\n`);
console.log(`artifacts.json from evm-contracts@${commit}: CancoreRouter ${out.CancoreRouter.bytecodeHash}`);
