#!/usr/bin/env node
// Generate the router-side golden vectors with ethers — an encoder this package
// does not ship — so the shipped helpers are checked against an independent
// implementation: spec/vectors/evm-order.json (hashOrder of an EVM-source
// order), spec/vectors/permit-witness.json (the Permit2 witness a maker signs
// for openFor) and spec/vectors/fee-split.json (the inclusive fee of
// protocol.md §3.11 on both rails). Deterministic: every input is a literal
// below or in protocol-fixtures.mjs, and a re-run rewrites byte-identical files.
//
//   node packages/contracts/scripts/gen-router-vectors.mjs
import { TypedDataEncoder } from 'ethers';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EVM_ORDER } from './protocol-fixtures.mjs';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = (rel, data) => {
  mkdirSync(dirname(join(pkg, rel)), { recursive: true });
  writeFileSync(join(pkg, rel), `${JSON.stringify(data, null, 2)}\n`);
};
const T = (fields) => fields.map(([type, name]) => ({ name, type }));
const ORDER = { Order: T([['address', 'user'], ['uint64', 'originChainId'], ['address', 'inputToken'], ['uint256', 'inputAmount'], ['bytes32', 'destination'], ['bytes32', 'outputAsset'], ['uint256', 'minReceived'], ['bytes32', 'recipient'], ['uint64', 'createdAt'], ['uint64', 'fillDeadline'], ['uint16', 'feeBps']]) };
const PERMIT = {
  PermitWitnessTransferFrom: T([['TokenPermissions', 'permitted'], ['address', 'spender'], ['uint256', 'nonce'], ['uint256', 'deadline'], ['Order', 'witness']]),
  TokenPermissions: T([['address', 'token'], ['uint256', 'amount']]),
  ...ORDER,
};
const PERMIT2_ADDRESS = '0x000000000022D473030F116dDEE9F6B43aC78BA3';
const constants = JSON.parse(readFileSync(join(pkg, 'spec', 'constants.json'), 'utf8'));
const router = (chainId, verifyingContract) => ({ name: 'CancoreRouter', version: '1', chainId, verifyingContract });

// --- evm-order.json: hashOrder of EVM-source orders in their source router's domain
const SEPOLIA_ROUTER = { chainId: '11155111', verifyingContract: '0x00000000000000000000000000000000cafe0001' };
const ARB_SEPOLIA_ROUTER = { chainId: '421614', verifyingContract: '0x00000000000000000000000000000000cafe0002' };
const reverseOrder = {
  ...EVM_ORDER,
  originChainId: '421614',
  inputToken: '0x75faf114eafb1bdbe2f0316df893fd58ce46aa4d',
  inputAmount: '110000000',
  destination: `0x${(11155111).toString(16).padStart(64, '0')}`,
  outputAsset: `0x${'0'.repeat(24)}1c7d4b196cb0c7b01d743fbc6116a902379c7238`,
  minReceived: '100000000',
  feeBps: '1000',
};
const orderRows = [
  { note: 'EVM-source fixture order (sepolia to arbitrum sepolia, 30 bps) — the same order and digest as spec/typed-data/Order.json', domain: SEPOLIA_ROUTER, order: EVM_ORDER },
  { note: 'the reverse route at MAX_FEE_BPS: 110 total, 100 net', domain: ARB_SEPOLIA_ROUTER, order: reverseOrder },
];
out('spec/vectors/evm-order.json', {
  $comment: 'EVM-source Order (protocol.md §3.3) and its orderHash = CancoreRouter.hashOrder in the source router domain {CancoreRouter, 1, chainId, verifyingContract}. Digests by ethers TypedDataEncoder; @cancore/contracts hashOrder must reproduce them. Generated by scripts/gen-router-vectors.mjs.',
  typeString: TypedDataEncoder.from(ORDER).encodeType('Order'),
  vectors: orderRows.map(({ note, domain, order }) => ({ note, domain, order, orderHash: TypedDataEncoder.hash(router(domain.chainId, domain.verifyingContract), ORDER, order) })),
});

// --- permit-witness.json: what the maker signs for openFor (CancoreRouter._pullInput)
const permitRows = [
  {
    note: 'the fixture order: permitted = its input token and total, spender = its source router, deadline = its fillDeadline (the router refuses a permit that outlives the order)',
    chainId: '11155111',
    message: { permitted: { token: EVM_ORDER.inputToken, amount: EVM_ORDER.inputAmount }, spender: SEPOLIA_ROUTER.verifyingContract, nonce: '1', deadline: EVM_ORDER.fillDeadline, witness: EVM_ORDER },
  },
  {
    note: 'the reverse route on arbitrum sepolia, a large unordered nonce',
    chainId: '421614',
    message: { permitted: { token: reverseOrder.inputToken, amount: reverseOrder.inputAmount }, spender: ARB_SEPOLIA_ROUTER.verifyingContract, nonce: '1790000000123456789', deadline: reverseOrder.fillDeadline, witness: reverseOrder },
  },
];
const typeString = TypedDataEncoder.from(PERMIT).encodeType('PermitWitnessTransferFrom');
const stub = 'PermitWitnessTransferFrom(TokenPermissions permitted,address spender,uint256 nonce,uint256 deadline,';
if (typeString !== stub + constants.contracts.CancoreRouter.WITNESS_TYPE_STRING.value) throw new Error('the witness type differs from CancoreRouter.WITNESS_TYPE_STRING');
out('spec/vectors/permit-witness.json', {
  $comment: 'The Permit2 PermitWitnessTransferFrom typed data a maker signs to open an EVM-source intent, the Order nested as witness; the type is the stub Permit2 prepends followed by CancoreRouter.WITNESS_TYPE_STRING (spec/constants.json). Domain {Permit2, chainId, verifyingContract = PERMIT2_ADDRESS}, no version. witnessHash = hashStruct(Order) = what openFor passes to Permit2. Digests by ethers TypedDataEncoder. Generated by scripts/gen-router-vectors.mjs.',
  typeString,
  types: PERMIT,
  vectors: permitRows.map(({ note, chainId, message }) => ({
    note, chainId, verifyingContract: PERMIT2_ADDRESS, message,
    witnessHash: TypedDataEncoder.hashStruct('Order', ORDER, message.witness),
    digest: TypedDataEncoder.hash({ name: 'Permit2', chainId, verifyingContract: PERMIT2_ADDRESS }, PERMIT, message),
  })),
});

// --- fee-split.json (protocol.md §3.11)
const evmSplit = (total, bps) => {
  const payout = (BigInt(total) * 10000n) / (10000n + BigInt(bps));
  return { payout: payout.toString(), fee: (BigInt(total) - payout).toString() };
};
const HH = 'evm-contracts test/CancoreRouter.ts @ c214f56';
const evm = [
  ['protocol.md §3.11 hand vector: 105 total at 5 % — 100 to the filler, 5 of fee (6 decimals)', '105000000', 500, `${HH}:1042`],
  ['the same at 18 decimals', '105000000000000000000', 500, `${HH}:1042`],
  ['feeBps = 0: the whole input is paid out', '100000000000000000000', 0, `${HH}:1058`],
  ['feeBps = MAX_FEE_BPS: 11 000 total, 10 000 net, 1 000 fee (1/11 of the total)', '11000', 1000, `${HH}:1066`],
  ['rounding dust on the fee: 12 345 at 33 bps pays 12 304, fee 41 (the ideal 40.6 rounded up)', '12345', 33, `${HH}:1079`],
  ['inexact division', '1000001', 7, `${HH}:1092`],
  ['inexact division', '999', 999, `${HH}:1092`],
  ['inexact division', '7', 1, `${HH}:1092`],
  ['dust below one net unit is all fee: 1 at MAX_FEE_BPS pays 0', '1', 1000, `${HH}:1100`],
  ['dust at a low rate: 1 at 30 bps pays 0', '1', 30, 'CAN-1934 acceptance'],
  ['11 at MAX_FEE_BPS: 10 and 1', '11', 1000, 'CAN-1934 acceptance'],
  ['10 000 at 0 bps', '10000', 0, 'CAN-1934 acceptance'],
  ['2^250 at MAX_FEE_BPS: no overflow (mulDiv)', (2n ** 250n).toString(), 1000, `${HH}:1112`],
  ['the fixture order: 1003 USDC at 30 bps is 1000 to the filler, 3 of fee (order.settled example)', EVM_ORDER.inputAmount, 30, 'spec/protocol/vectors/messages.json'],
].map(([note, total, feeBps, pinnedBy]) => ({ note, total, feeBps, ...evmSplit(total, feeBps), pinnedBy }));

// Canton source: payout = roundHalfEven(T × 10 000 / (10 000 + feeBps)); the Daml values are protocol.md §3.11's,
// from `daml test` of the inclusiveFee body (canton-contracts intent/daml/Intent/SwapIntent.daml:288-289).
const cantonRows = [
  ['worked: 1000.0 at 0.003', '1000.0', '0.003', '997.0089730808', '2.9910269192'],
  ['same as EVM: 105.0 at 0.05', '105.0', '0.05', '100.0', '5.0'],
  ['tie, q even, kept', '100.8000000063', '0.008', '100.0000000062', '0.8000000001'],
  ['tie, q odd, rounded up', '100.8000000189', '0.008', '100.0000000188', '0.8000000001'],
  ['dust: 0.0000000002 at 0.1 is all payout', '0.0000000002', '0.1', '0.0000000002', '0.0'],
];
const units10 = (d) => {
  const [w, f = ''] = d.split('.');
  return BigInt(w + f.padEnd(10, '0'));
};
const canton = cantonRows.map(([note, amount, feeRate, ledgerPayout, ledgerFee]) => {
  const total = units10(amount);
  const feeBps = Number(units10(feeRate) / 1_000_000n);
  const n = total * 10000n;
  const d = 10000n + BigInt(feeBps);
  const q = n / d;
  const r = n - q * d;
  const payout = 2n * r > d || (2n * r === d && q % 2n === 1n) ? q + 1n : q;
  if (payout !== units10(ledgerPayout) || total - payout !== units10(ledgerFee)) throw new Error(`canton case "${note}" disagrees with the Daml values`);
  return { note, amount, feeRate, total: total.toString(), feeBps, payout: payout.toString(), fee: (total - payout).toString(), ledgerPayout, ledgerFee, evmPayout: evmSplit(total, feeBps).payout };
});
out('spec/vectors/fee-split.json', {
  $comment: 'The inclusive fee of protocol.md §3.11: the maker hands over the total T, the filler is paid `payout`, Cancore keeps `fee` = T − payout. evm: CancoreRouter.settle, payout = floor(T × 10000 / (10000 + feeBps)) — each case names the router test that pins it (pinnedBy). canton: Daml inclusiveFee in EVM-form units (T = amount × 10^10, feeBps = feeRate × 10000), payout = the same quotient rounded half to even; ledgerPayout/ledgerFee are the Daml Decimal values (protocol.md §3.11), evmPayout the EVM formula for comparison. Generated by scripts/gen-router-vectors.mjs.',
  evm,
  canton,
});
console.log(`router vectors written: ${orderRows.length} orders, ${permitRows.length} permits, ${evm.length} + ${canton.length} fee cases`);
