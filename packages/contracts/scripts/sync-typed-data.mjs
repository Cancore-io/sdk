#!/usr/bin/env node
// Pull the EIP-712 schemas the Cancore contracts verify signatures over out of a
// checkout of Cancore-io/evm-contracts (abi/typed-data/*.json) and write this
// package's copy: the JSON, golden vectors included, under spec/typed-data/, and
// the types as `as const` TypeScript under src/generated/typedData.ts.
//
// Separate from sync.mjs so a schema can be refreshed without re-syncing every
// ABI; `npm run sync` runs both. Nothing here is edited by hand.
//
//   EVM_CONTRACTS_DIR=../evm-contracts npm run sync
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const src = resolve(process.env.EVM_CONTRACTS_DIR ?? resolve(pkg, '../../../evm-contracts'), 'abi', 'typed-data');

const files = readdirSync(src).filter((f) => f.endsWith('.json')).sort();
if (files.length === 0) throw new Error(`no typed-data schemas under ${src}`);
mkdirSync(join(pkg, 'spec', 'typed-data'), { recursive: true });

const constName = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
const blocks = [];
for (const file of files) {
  const schema = JSON.parse(readFileSync(join(src, file), 'utf8'));
  writeFileSync(join(pkg, 'spec', 'typed-data', file), `${JSON.stringify(schema, null, 2)}\n`);
  const id = constName(schema.primaryType);
  blocks.push(
    `/** \`${schema.typeString}\` — from evm-contracts/abi/typed-data/${file}. */\n` +
      `export const ${id}_TYPES = ${JSON.stringify(schema.types, null, 2)} as const;\n\n` +
      `export const ${id}_TYPE_STRING = ${JSON.stringify(schema.typeString)};\n\n` +
      `/** Name and version of the domain; chain id and verifying contract are the deployment's. */\n` +
      `export const ${id}_DOMAIN = ${JSON.stringify({ name: schema.domain.name, version: schema.domain.version })} as const;\n`,
  );
}
writeFileSync(
  join(pkg, 'src', 'generated', 'typedData.ts'),
  `// Generated by scripts/sync-typed-data.mjs from evm-contracts/abi/typed-data — do not edit.\n\n${blocks.join('\n')}`,
);
console.log(`synced ${files.length} typed-data schema(s) from ${src}`);
