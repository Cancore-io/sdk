#!/usr/bin/env node
// Derive the example frames, the fixture records and the AsyncAPI document of
// filler protocol v1 from the JSON Schemas and the golden vectors — run after
// gen-protocol-vectors.mjs. Every example is validated against its schema
// before it is written, so a broken example never lands.
//
//   node packages/contracts/scripts/gen-protocol-docs.mjs
import Ajv2020 from 'ajv/dist/2020.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { drawRecord, epochRecord, messageExamples, PLACEHOLDER_SIG } from './protocol-examples.mjs';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (...p) => JSON.parse(readFileSync(join(pkg, 'spec', ...p), 'utf8'));
const write = (rel, data) => writeFileSync(join(pkg, 'spec', rel), `${JSON.stringify(data, null, 2)}\n`);

const schemas = { messages: read('protocol', 'messages.schema.json'), rest: read('protocol', 'rest.schema.json'), records: read('protocol', 'records.schema.json') };
const ajv = new Ajv2020({ strict: true, allErrors: true });
ajv.addVocabulary(['x-direction', 'x-endpoints', 'x-error-status']);
for (const s of Object.values(schemas)) ajv.addSchema(s);
const check = (ref, value) => {
  if (!ajv.validate(ref, value)) throw new Error(`${ref}: ${ajv.errorsText()}\n${JSON.stringify(value)}`);
};

const td = (name, dir = 'protocol/typed-data') => read(...dir.split('/'), `${name}.json`).vectors;
const orderVec = td('Order', 'typed-data')[1];
const ticketVec = td('FillTicket', 'typed-data')[1];
const draw = read('protocol', 'vectors', 'draw.json').vectors[1];
const epoch = epochRecord();
const examples = messageExamples({
  order: orderVec.message,
  orderHash: orderVec.digest,
  ticket: ticketVec.message,
  ticketHash: ticketVec.digest,
  quoteHash: td('FillerQuote')[0].digest,
  intentHash: td('TicketIntent')[0].digest,
  receiptSigHash: td('TicketReceipt')[0].message.ticketSigHash,
  offerBody: td('GatewayMessage')[0].body,
  epoch,
});

const MSG = 'https://cancore.io/schemas/filler-protocol/v1/messages.schema.json#/$defs/';
const REC = 'https://cancore.io/schemas/filler-protocol/v1/records.schema.json#/$defs/';
const types = Object.entries(schemas.messages.$defs).filter(([, d]) => d['x-direction']).map(([name]) => name);
for (const type of types) {
  if (!examples[type]?.length) throw new Error(`no example for ${type}`);
  for (const e of examples[type]) check(`${MSG}${type}`, e);
}
write('protocol/vectors/messages.json', {
  $comment: 'Valid example frames of filler protocol v1, one or more per type, built on the golden vectors (hashes are real). sig is a zero placeholder: @cancore/test-kit signs what it serves. Generated by scripts/gen-protocol-docs.mjs.',
  examples,
});

const records = { draw: drawRecord(draw), epoch };
check(`${REC}drawRecord`, { ...records.draw, sig: PLACEHOLDER_SIG });
check(`${REC}epochRecord`, { ...records.epoch, sig: PLACEHOLDER_SIG });
write('protocol/vectors/records.json', {
  $comment: 'Fixture draw record (attempt 0 of the test-kit fixture order, spec/protocol/vectors/draw.json) and the epoch record containing its t0, without sig — the gateway signs them. weightsRoot: OpenZeppelin StandardMerkleTree over ["string","uint256","uint8","uint16"] = (fillerId, base, tier, reliabilityBps); weight = (base + step(tier)) × reliabilityBps.',
  ...records,
});

// AsyncAPI 3.0, from the gateway's side: it sends S2F frames and receives F2S ones. A type that
// goes both ways (ping, pong) is two messages, <type>S2F (signed) and <type>F2S, each with its $def.
const dirs = Object.fromEntries(types.map((t) => [t, schemas.messages.$defs[t]['x-direction']]));
const messageKeys = types.flatMap((t) => (dirs[t] === 'both' ? [`${t}S2F`, `${t}F2S`] : [t]));
const wireType = (key) => (dirs[key] ? key : key.slice(0, -3));
const dirOf = (key) => dirs[key] ?? key.slice(-3);
const examplesOf = (key) => examples[wireType(key)].filter((e) => dirs[key] || ('sig' in e) === (dirOf(key) === 'S2F'));
for (const key of messageKeys.filter((k) => !dirs[k])) {
  if (!examplesOf(key).length) throw new Error(`no example for ${key}`);
  for (const e of examplesOf(key)) check(`${MSG}${key}`, e);
}
const opName = (action, type) => `${action}${type.split(/[.-]/).map((w) => w[0].toUpperCase() + w.slice(1)).join('')}`;
const operations = {};
for (const key of messageKeys) {
  const action = dirOf(key) === 'S2F' ? 'send' : 'receive';
  operations[opName(action, wireType(key))] = { action, channel: { $ref: '#/channels/filler' }, messages: [{ $ref: `#/channels/filler/messages/${key}` }] };
}
write('protocol/asyncapi.json', {
  asyncapi: '3.0.0',
  info: {
    title: 'Cancore filler protocol',
    version: '1.0.0-rc.1',
    description: 'The WebSocket protocol between a taker (filler) and the Cancore filler gateway, v1 (release candidate, @cancore/contracts 0.2.0-rc.1). Operations are the gateway\'s: it sends S→F frames and receives F→S frames. Every S→F frame carries fillerId, sentAt and sig = the gateway key over GatewayMessage{bodyHash} in the CancoreFillerProtocol v1 domain. Payload schemas: messages.schema.json. Generated by scripts/gen-protocol-docs.mjs.',
    license: { name: 'Apache-2.0' },
  },
  defaultContentType: 'application/json',
  servers: {
    mock: { host: 'localhost:{port}', protocol: 'ws', description: '@cancore/test-kit mock-gateway', variables: { port: { default: '8787' } } },
    devnet: { host: '{gatewayHost}', protocol: 'wss', description: 'Published per environment (O-6)', variables: { gatewayHost: { default: 'filler.dev.cancore.io' } } },
  },
  channels: {
    filler: {
      address: '/v1',
      description: 'One JSON object per text frame. Nothing but auth.* and error flows before auth.ok; FillerAuth in auth.response authenticates the socket (the REST fallback uses a bearer token).',
      messages: Object.fromEntries(messageKeys.map((k) => [k, { $ref: `#/components/messages/${k}` }])),
    },
  },
  operations,
  components: {
    messages: Object.fromEntries(
      messageKeys.map((k) => [
        k,
        {
          name: wireType(k),
          title: `${wireType(k)} (${dirOf(k)})`,
          payload: { schemaFormat: 'application/schema+json;version=draft-2020-12', schema: { $ref: `messages.schema.json#/$defs/${k}` } },
          examples: examplesOf(k).map((payload, i) => ({ name: `${k.replace(/\./g, '-')}-${i + 1}`, payload })),
        },
      ]),
    ),
  },
});
console.log(`${types.length} frame types, ${messageKeys.length} messages, ${Object.keys(operations).length} operations`);
