// Regenerates src/cantonDestination.attestor.test.ts: the expected values come from running the
// attestor's own src/canton.ts (not this package) on a fixed input set. Not part of `npm run vectors`
// (CI has no attestor checkout); run by hand when the inputs change or the attestor formulas change:
//   node packages/contracts/scripts/regen-attestor-vector.mjs <path to a Cancore-io/attestor checkout>
// Needs node >= 22.18 (runs the attestor's .ts directly) and `ethers` resolvable from the attestor
// checkout (6.17.0 was used; the same version is pinned in this repo). Review the diff of the test file.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const dir = resolve(process.argv[2] ?? '');
if (!process.argv[2]) throw new Error('usage: regen-attestor-vector.mjs <attestor checkout>');
const git = (...args) => execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim();
const { cantonDestination, instrumentAsset, partyRecipient, decimalUnits } = await import(pathToFileURL(join(dir, 'src', 'canton.ts')));
const ethersVersion = JSON.parse(readFileSync(join(dir, 'node_modules', 'ethers', 'package.json'), 'utf8')).version;

const fingerprint = `1220${'ab'.repeat(32)}`;
const networks = ['mainnet', 'testnet', 'devnet'];
const instruments = [
  [`DSO::${fingerprint}`, 'Amulet'],
  [`USDCx-admin::${fingerprint}`, 'USDCx'],
  ['a', 'b'],
  ['x'.repeat(33), 'y'.repeat(64)],
  [`adm::${fingerprint}`, 'Токен-ü'],
];
const parties = [`alice::${fingerprint}`, `PAR::TY::${fingerprint}`, 'p', 'q'.repeat(130), `Алиса::${fingerprint}`];
const amounts = [
  '0', '0.0', '1', '1.5', '0.0000000001', '1.0000000001', '42', '42.0123456789', '12345.1234567890', '007.50',
  '34028236692093846346337460743.1768211455', // 2^128 - 1 units: 29 integer digits with 10 fraction digits
  '99999999999999999999.9999999999',
  '340282366920938463463374607431768211455', // 39 integer digits
];
const refused = ['1.00000000001', '-1', '1e3', '', '1,5', ' 1', '1.', '.5', '0x10'];

// One TS literal in the repository style: single quotes, unquoted keys.
const lit = (v) => {
  if (typeof v === 'string') return `'${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (Array.isArray(v)) return `[${v.map(lit).join(', ')}]`;
  return `{ ${Object.entries(v).map(([k, x]) => `${k}: ${lit(x)}`).join(', ')} }`;
};
const rows = (items) => `[\n${items.map((r) => `  ${lit(r)},`).join('\n')}\n]`;

const destinations = Object.fromEntries(networks.map((n) => [n, cantonDestination(n)]));
const assets = instruments.map(([admin, id]) => ({ admin, id, outputAsset: instrumentAsset(admin, id) }));
const recipients = parties.map((party) => ({ party, recipient: partyRecipient(party) }));
const units = amounts.map((amount) => ({ amount, units: decimalUnits(amount).toString() }));
for (const bad of refused) {
  let threw = false;
  try { decimalUnits(bad); } catch { threw = true; }
  if (!threw) throw new Error(`the attestor accepts ${JSON.stringify(bad)}: move it out of the refused list`);
}

const head = git('rev-parse', 'HEAD');
const touched = git('log', '-1', '--format=%H', '--', 'src/canton.ts');
const out = `import { encodeCantonAmount, encodeCantonDestination, encodeCantonOutputAsset, encodeCantonRecipient } from './cantonDestination';

// GENERATED by scripts/regen-attestor-vector.mjs: do not edit by hand, rerun the script.
//
// A pinned snapshot of the attestor's Canton encoding (CAN-1935). The expected values below were NOT
// produced by this package: they come from running the attestor's own implementation (cantonDestination,
// instrumentAsset, partyRecipient, decimalUnits in src/canton.ts) unmodified.
//   generated from Cancore-io/attestor at ${head} (ethers ${ethersVersion});
//   src/canton.ts was last changed in ${touched}.
//
// What this does NOT prove:
//   - The values are frozen. If the attestor later changes these formulas, this test stays green: the
//     attestor's own test recomputes the formula with the same expression, so it cannot catch it either.
//     Drift protection needs the same vector on the attestor side (tracked separately).
//   - The CAN-1935 acceptance line says the vector matches "the attestor's and Daml's encoding". Only the
//     attestor half is checked here; no comparison with the Daml encoding exists, that part stays open.

const DESTINATIONS = {\n${Object.entries(destinations).map(([n, d]) => `  ${n}: ${lit(d)},`).join('\n')}\n} as const;

const INSTRUMENTS = ${rows(assets)};

const PARTIES = ${rows(recipients)};

// Daml Numeric 10: 0 and 10 fraction digits, leading zeros, the 2^128 - 1 units boundary. The last two
// amounts have more integer digits than Numeric 10 allows (28); neither implementation limits them.
const AMOUNTS = ${rows(units)};

// Refused by the attestor's decimalUnits (it throws); this encoder must refuse them as well.
const REFUSED = ${lit(refused)};

describe("encoder equals the attestor's implementation (pinned outputs)", () => {
  test.each(Object.entries(DESTINATIONS))('destination of canton:%s', (network, expected) => {
    expect(encodeCantonDestination(network as keyof typeof DESTINATIONS)).toBe(expected);
  });

  test.each(INSTRUMENTS)('outputAsset of $admin / $id', ({ admin, id, outputAsset }) => {
    expect(encodeCantonOutputAsset({ admin, id })).toBe(outputAsset);
  });

  test.each(PARTIES)('recipient of party $party', ({ party, recipient }) => {
    expect(encodeCantonRecipient(party)).toBe(recipient);
  });

  test.each(AMOUNTS)('amountDelivered of $amount', ({ amount, units }) => {
    expect(encodeCantonAmount(amount)).toBe(BigInt(units));
  });

  test.each(REFUSED)('refuses %j like the attestor', (bad) => {
    expect(() => encodeCantonAmount(bad)).toThrow();
  });
});
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'cantonDestination.attestor.test.ts'), out);
console.log(`wrote the test from attestor ${head}`);
